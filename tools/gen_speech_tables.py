#!/usr/bin/env python3
"""Extract the TMS5200/CD2501E coefficient tables from MAME's tms5110r.hxx
and emit a C header.  Usage: gen_speech_tables.py tms5110r.hxx out.h"""
import re, sys

src = open(sys.argv[1]).read()

def macro(name):
    m = re.search(r'#define\s+' + name + r'\s*\\\n(.*?)(?:\n\s*\n|\n/\*|\n#define|\n//)', src, re.S)
    if not m:
        raise SystemExit("macro %s not found" % name)
    body = m.group(1)
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)     # block comments
    body = re.sub(r'//[^\n]*', '', body)                   # line comments
    return body.replace('\\', ' ')

def ints(text):
    return [int(x, 0) for x in re.findall(r'-?0x[0-9a-fA-F]+|-?\d+', text)]

energy = ints(macro('TI_028X_LATER_ENERGY'))
pitch  = ints(macro('TI_2501E_PITCH'))
chirp  = ints(macro('TI_LATER_CHIRP'))
interp = ints(macro('TI_INTERP'))
lpc    = macro('TI_2801_2501E_LPC')
ks = [ints(g) for g in re.findall(r'\{([^{}]*)\}', lpc)]

assert len(energy) == 16, len(energy)
assert len(pitch) == 64, len(pitch)
assert len(chirp) == 52, len(chirp)
assert interp == [0, 3, 3, 3, 2, 2, 1, 1], interp
assert [len(k) for k in ks] == [32, 32, 16, 16, 16, 16, 16, 8, 8, 8], [len(k) for k in ks]
assert sum(chirp) == 0x3da, hex(sum(chirp))                 # MAME: "sum = 0x3da" verified against decap
assert energy[0] == 0 and energy[15] == 0 and energy == sorted(energy[:15]) + [0]
assert pitch[0] == 0 and pitch[1:] == sorted(pitch[1:])
for i, k in enumerate(ks):                                  # K tables are monotonic except the known K2 clamp entry
    body = k[:-1] if i == 1 else k
    assert body == sorted(body), "K%d not monotonic" % (i + 1)
assert all(-512 <= v <= 511 for k in ks for v in k)

def arr(name, ctype, vals, per=8):
    rows = []
    for i in range(0, len(vals), per):
        rows.append('    ' + ', '.join('%4d' % v for v in vals[i:i + per]))
    return 'static const %s %s[%d] = {\n%s\n};\n' % (ctype, name, len(vals), ',\n'.join(rows))

out = ['/* GENERATED by tools/gen_speech_tables.py from MAME src/devices/sound/tms5110r.hxx',
       ' * (TI_028X_LATER_ENERGY, TI_2501E_PITCH, TI_2801_2501E_LPC, TI_LATER_CHIRP, TI_INTERP).',
       ' * Hardware ROM contents of the TMS5200 / CD2501E (TMC0285), verified against decaps by',
       ' * the MAME authors.  See third_party/MAME-NOTICE.txt.  Do not edit by hand. */',
       '#ifndef SPEECH_TABLES_H', '#define SPEECH_TABLES_H', '#include <stdint.h>', '']
out.append(arr('sp_energy_tab', 'uint16_t', energy))
out.append(arr('sp_pitch_tab', 'uint16_t', pitch))
out.append(arr('sp_chirp_tab', 'int8_t', chirp))
out.append(arr('sp_interp_shift', 'uint8_t', interp))
for i, k in enumerate(ks):
    out.append(arr('sp_k%d_tab' % (i + 1), 'int16_t', k))
out.append('static const int16_t *const sp_k_tab[10] = { ' + ', '.join('sp_k%d_tab' % (i + 1) for i in range(10)) + ' };')
out.append('static const uint8_t sp_k_bits[10] = { 5, 5, 4, 4, 4, 4, 4, 3, 3, 3 };')
out.append('')
out.append('#endif')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print("ok: energy %d pitch %d chirp %d K sizes %s chirp-sum %#x" % (len(energy), len(pitch), len(chirp), [len(k) for k in ks], sum(chirp)))
