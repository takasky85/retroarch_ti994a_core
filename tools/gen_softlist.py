#!/usr/bin/env python3
"""Trim MAME's hash/ti99_cart.xml (CC0-1.0) to the attributes the loader needs and emit a C byte array.
Usage: gen_softlist.py ti99_cart.xml out.h"""
import sys, xml.etree.ElementTree as ET
root = ET.parse(sys.argv[1]).getroot()
parts = []
n = 0
for sw in root.findall('software'):
    p = sw.find('part')
    if p is None or p.get('interface') != 'ti99_cart':
        continue
    s = '<software name="%s"><part interface="ti99_cart">' % sw.get('name')
    for f in p.findall('feature'):
        if f.get('name') == 'pcb':
            s += '<feature name="pcb" value="%s"/>' % f.get('value')
    for d in p.findall('dataarea'):
        s += '<dataarea name="%s" size="%s">' % (d.get('name'), d.get('size'))
        for r in d.findall('rom'):
            s += '<rom name="%s" size="%s" offset="%s"/>' % (r.get('name'), r.get('size'), r.get('offset'))
        s += '</dataarea>'
    s += '</part></software>\n'
    parts.append(s); n += 1
blob = ''.join(parts).encode('ascii')
lines = []
for i in range(0, len(blob), 24):
    lines.append('  ' + ','.join('0x%02x' % b for b in blob[i:i + 24]))
open(sys.argv[2], 'w').write(
    '/* GENERATED by tools/gen_softlist.py from MAME hash/ti99_cart.xml (license: CC0-1.0).\n'
    ' * %d cartridges; trimmed to name / pcb type / dataareas / rom file names, sizes and offsets. */\n'
    '#ifndef SOFTLIST_DATA_H\n#define SOFTLIST_DATA_H\nstatic const char softlist_xml[] = {\n%s,\n  0x00\n};\n#endif\n'
    % (n, ',\n'.join(lines)))
print("entries", n, "bytes", len(blob))
